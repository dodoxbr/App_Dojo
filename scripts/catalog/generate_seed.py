"""Generates the catalog seed migration and the review report from the staging CSV.

Deterministic: same CSV -> same SQL (stable UUIDs, fixed review date). Standard library only.
Usage: python -I scripts/catalog/generate_seed.py

Merge rule: only techniques whose NORMALIZED name AND category are identical are merged (all source
rows are kept as provenance). Similar-but-different names are never merged; they are listed in the
report for human review (docs/08: no automatic heuristic merging).
"""
import csv
import difflib
import re
import unicodedata
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STAGING = ROOT / "data" / "catalog" / "techniques_staging.csv"
SEED = ROOT / "supabase" / "migrations" / "202610200007_seed_catalog.sql"
REPORT = ROOT / "data" / "catalog" / "IMPORT_REPORT.md"

NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "https://github.com/dodoxbr/App_Dojo/catalog")
SOURCE = "Plano de Treino_Básico ao Avançado.xlsx"
REVIEWED_AT = "2026-10-20T00:00:00Z"  # review declared by the product owner on this date
LEVEL_ORDER = {"Básico": 0, "Intermediário": 1, "Avançado": 2}


def norm(text):
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    return re.sub(r"\s+", " ", text).strip().lower()


def q(text):
    return "'" + text.replace("'", "''") + "'"


def main():
    rows = list(csv.DictReader(STAGING.open(encoding="utf-8")))
    rows.sort(key=lambda r: (LEVEL_ORDER[r["level"]], int(r["source_row"]), int(r["source_col"])))

    techniques = {}  # key -> dict
    for r in rows:
        key = (norm(r["category"]), norm(r["raw_name"]))
        t = techniques.get(key)
        if t is None:
            t = techniques[key] = {
                "id": uuid.uuid5(NAMESPACE, "technique|%s|%s" % key),
                "name": r["raw_name"],
                "category": r["category"],
                "level": r["level"],  # first (lowest) level where it appears
                "sources": [],
            }
        t["sources"].append(r)

    lines = [
        "-- GENERATED by scripts/catalog/generate_seed.py from data/catalog/techniques_staging.csv. Do not edit by hand.",
        "-- Global technique catalog imported from the reviewed spreadsheet (US-005). Stable ids; idempotent.",
        "insert into public.techniques (id, academy_id, name, category, level, source, reviewed_at) values",
    ]
    values = [
        "  (%s, null, %s, %s, %s, %s, %s)"
        % (q(str(t["id"])), q(t["name"]), q(t["category"]), q(t["level"]), q(SOURCE), q(REVIEWED_AT))
        for t in techniques.values()
    ]
    lines.append(",\n".join(values))
    lines.append("on conflict (id) do nothing;\n")

    lines.append(
        "insert into public.technique_sources "
        "(id, technique_id, source, sheet, source_row, source_col, source_number, raw_name, level, belt) values"
    )
    src_values = []
    for t in techniques.values():
        for s in t["sources"]:
            sid = uuid.uuid5(NAMESPACE, "source|%s|%s|%s" % (s["source_sheet"], s["source_row"], s["source_col"]))
            src_values.append(
                "  (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)"
                % (
                    q(str(sid)), q(str(t["id"])), q(SOURCE), q(s["source_sheet"]), s["source_row"], s["source_col"],
                    s["source_number"], q(s["raw_name"]), q(s["level"]), q(s["belt"]),
                )
            )
    lines.append(",\n".join(src_values))
    lines.append("on conflict (id) do nothing;\n")
    SEED.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    # ---- review report -------------------------------------------------------------------
    merged = [t for t in techniques.values() if len(t["sources"]) > 1]
    by_name = {}
    for (cat, name), t in techniques.items():
        by_name.setdefault(name, []).append(t)
    same_name_other_category = {n: ts for n, ts in by_name.items() if len(ts) > 1}

    names = [(t["name"], t["category"], norm(t["name"])) for t in techniques.values()]
    near = []
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            a, b = names[i], names[j]
            if a[2] == b[2]:
                continue
            ratio = difflib.SequenceMatcher(None, a[2], b[2]).ratio()
            if ratio >= 0.88:
                near.append((ratio, a, b))
    near.sort(reverse=True)

    out = [
        "# Relatório da importação do catálogo (US-005)",
        "",
        "Gerado por `scripts/catalog/generate_seed.py`. Origem: `%s` (abas Básico, Intermediário, Avançado)." % SOURCE,
        "Revisão declarada pelo dono do produto em 2026-10-20. Abas ocultas e `Material de Estudo` **não** foram importadas.",
        "",
        "## Totais",
        "- Linhas extraídas: **%d**" % len(rows),
        "- Técnicas únicas no catálogo global: **%d**" % len(techniques),
        "- Técnicas que aparecem em mais de um nível (nome e categoria idênticos): **%d**" % len(merged),
        "",
        "## Nomes iguais em categorias diferentes (mantidos como técnicas distintas)",
    ]
    if same_name_other_category:
        for n, ts in sorted(same_name_other_category.items()):
            out.append("- %s: %s" % (ts[0]["name"], "; ".join(sorted(t["category"] for t in ts))))
    else:
        out.append("- Nenhum.")
    out += ["", "## Grafias parecidas, NÃO fundidas (revisar com o mestre)", ""]
    if near:
        out += ["| Semelhança | Nome A | Categoria A | Nome B | Categoria B |", "|---|---|---|---|---|"]
        for ratio, a, b in near:
            out.append("| %.2f | %s | %s | %s | %s |" % (ratio, a[0], a[1], b[0], b[1]))
    else:
        out.append("Nenhuma.")
    out += [
        "",
        "## Observações sobre a origem",
        "- O número 45 aparece duas vezes em `Quedas` nas abas Básico e Intermediário; o número original é mantido em `technique_sources.source_number`.",
        "- Na aba Avançado o bloco `Chaves Membros Inferiores` é numerado de 90 a 94 (a numeração salta de 54 para 90).",
        "- Nomes foram importados como escritos (apenas espaços normalizados). Erros de digitação aparentes (por exemplo `Pluso`, `Estragulamento`, `Armlok`) devem ser corrigidos por edição, não pela importação.",
        "- A marca `x` e a contagem `Acertos` da planilha são controles de avaliação e não foram importadas.",
        "- A faixa citada em cada aba (BRANCA, AZUL, ROXA) fica na proveniência (`belt`); não foi interpretada como regra de graduação.",
        "",
    ]
    REPORT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(techniques)} técnicas, {len(rows)} origens; {len(merged)} em mais de um nível; {len(near)} pares parecidos")


if __name__ == "__main__":
    main()
