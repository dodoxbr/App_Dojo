"""Generates the catalog migrations and the review report from the staging CSV and the review files.

Deterministic: same inputs -> same SQL (stable UUIDs, fixed review date). Standard library only.
Usage: python -I scripts/catalog/generate_seed.py

Outputs
- 202610200007_seed_catalog.sql: techniques exactly as written in the spreadsheet (+ provenance).
- 202610200009_catalog_corrections.sql: typo fixes (data/catalog/name_corrections.csv) and the
  type/position classification proposed from public sources (data/catalog/classification.csv).
- data/catalog/IMPORT_REPORT.md

Merge rule: only techniques whose NORMALIZED name AND category are identical are merged (all source
rows are kept as provenance). Similar-but-different names are never merged; they are listed in the
report for human review (docs/08: no automatic heuristic merging). Technique ids are derived from the
ORIGINAL spreadsheet names, so corrections never change an id.
"""
import csv
import difflib
import re
import unicodedata
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data" / "catalog"
STAGING = DATA / "techniques_staging.csv"
CORRECTIONS = DATA / "name_corrections.csv"
CLASSIFICATION = DATA / "classification.csv"
FLAGGED = DATA / "flagged_for_confirmation.csv"
SEED = ROOT / "supabase" / "migrations" / "202610200007_seed_catalog.sql"
FIXES = ROOT / "supabase" / "migrations" / "202610200009_catalog_corrections.sql"
REPORT = DATA / "IMPORT_REPORT.md"

NAMESPACE = uuid.uuid5(uuid.NAMESPACE_URL, "https://github.com/dodoxbr/App_Dojo/catalog")
SOURCE = "Plano de Treino_Básico ao Avançado.xlsx"
REVIEWED_AT = "2026-10-20T00:00:00Z"  # review declared by the product owner on this date
LEVEL_ORDER = {"Básico": 0, "Intermediário": 1, "Avançado": 2}
CONFIDENCE_PT = {"alta": "alta", "media": "média", "baixa": "baixa"}


def norm(text):
    text = unicodedata.normalize("NFKD", text)
    text = "".join(ch for ch in text if not unicodedata.combining(ch))
    return re.sub(r"\s+", " ", text).strip().lower()


def q(text):
    return "'" + text.replace("'", "''") + "'"


def read_csv(path):
    return list(csv.DictReader(path.open(encoding="utf-8")))


def main():
    rows = read_csv(STAGING)
    rows.sort(key=lambda r: (LEVEL_ORDER[r["level"]], int(r["source_row"]), int(r["source_col"])))

    techniques = {}  # (category, name) normalized -> dict
    for r in rows:
        key = (norm(r["category"]), norm(r["raw_name"]))
        t = techniques.get(key)
        if t is None:
            t = techniques[key] = {
                "id": uuid.uuid5(NAMESPACE, "technique|%s|%s" % key),
                "name": r["raw_name"],
                "category": r["category"],
                "level": r["level"],  # first (lowest) level where it appears
                "sources": [],
            }
        t["sources"].append(r)

    # ---- 007: seed exactly as written in the spreadsheet -------------------------------------
    lines = [
        "-- GENERATED by scripts/catalog/generate_seed.py from data/catalog/techniques_staging.csv. Do not edit by hand.",
        "-- Global technique catalog imported from the reviewed spreadsheet (US-005). Stable ids; idempotent.",
        "insert into public.techniques (id, academy_id, name, category, level, source, reviewed_at) values",
    ]
    lines.append(
        ",\n".join(
            "  (%s, null, %s, %s, %s, %s, %s)"
            % (q(str(t["id"])), q(t["name"]), q(t["category"]), q(t["level"]), q(SOURCE), q(REVIEWED_AT))
            for t in techniques.values()
        )
    )
    lines.append("on conflict (id) do nothing;\n")
    lines.append(
        "insert into public.technique_sources "
        "(id, technique_id, source, sheet, source_row, source_col, source_number, raw_name, level, belt) values"
    )
    src_values = []
    for t in techniques.values():
        for s in t["sources"]:
            sid = uuid.uuid5(NAMESPACE, "source|%s|%s|%s" % (s["source_sheet"], s["source_row"], s["source_col"]))
            src_values.append(
                "  (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s)"
                % (
                    q(str(sid)), q(str(t["id"])), q(SOURCE), q(s["source_sheet"]), s["source_row"], s["source_col"],
                    s["source_number"], q(s["raw_name"]), q(s["level"]), q(s["belt"]),
                )
            )
    lines.append(",\n".join(src_values))
    lines.append("on conflict (id) do nothing;\n")
    SEED.write_text("\n".join(lines), encoding="utf-8", newline="\n")

    # ---- 009: corrections + classification ---------------------------------------------------
    corrections = read_csv(CORRECTIONS)
    corrected_name = {}  # technique id -> new name
    final_keys = {k: t for k, t in techniques.items()}
    for c in corrections:
        key = (norm(c["category"]), norm(c["old_name"]))
        t = techniques.get(key)
        if t is None:
            raise SystemExit(f"Correção sem técnica correspondente: {c['category']} / {c['old_name']}")
        if t["name"] != c["old_name"]:
            raise SystemExit(f"Nome antigo difere do original da planilha: {t['name']!r} != {c['old_name']!r}")
        new_key = (key[0], norm(c["new_name"]))
        if new_key != key and new_key in final_keys:
            raise SystemExit(f"Correção causaria duplicata: {c['category']} / {c['new_name']}")
        if t["id"] in corrected_name:
            raise SystemExit(f"Técnica corrigida duas vezes: {c['old_name']}")
        final_keys.pop(key)
        final_keys[new_key] = t
        corrected_name[t["id"]] = (c["old_name"], c["new_name"], c["reason"])

    classification = read_csv(CLASSIFICATION)
    classified = []
    seen = set()
    for c in classification:
        key = (norm(c["category"]), norm(c["name"]))
        t = techniques.get(key)
        if t is None:
            raise SystemExit(f"Classificação sem técnica correspondente: {c['category']} / {c['name']}")
        if key in seen:
            raise SystemExit(f"Classificação duplicada: {c['name']}")
        seen.add(key)
        if c["technique_type"] or c["position"]:
            note = "Proposto por pesquisa em fontes públicas; não validado pelo mestre. Confiança: %s." % CONFIDENCE_PT[c["confidence"]]
            if c["basis"]:
                note += " Base: %s." % c["basis"]
            if c["reference"]:
                note += " Fontes: %s." % c["reference"]
            classified.append((t["id"], c["technique_type"] or None, c["position"] or None, note))
    if len(seen) != len(techniques):
        missing = [t["name"] for k, t in techniques.items() if k not in seen]
        raise SystemExit(f"Técnicas sem linha em classification.csv: {missing}")

    fx = [
        "-- GENERATED by scripts/catalog/generate_seed.py. Do not edit by hand.",
        "-- Typo fixes requested by the product owner (the original names stay in technique_sources.raw_name;",
        "-- the techniques keep their review) and type/position PROPOSED from public sources (not validated).",
    ]
    for tid, (old, new, reason) in corrected_name.items():
        fx.append("-- %s -> %s (%s)" % (old, new, reason))
        fx.append("update public.techniques set name = %s where id = %s and name = %s;" % (q(new), q(str(tid)), q(old)))
    fx.append("")
    fx.append("update public.techniques t set technique_type = v.technique_type, technique_position = v.technique_position,")
    fx.append("  classification_status = 'proposed', classification_source = v.note")
    fx.append("from (values")
    fx.append(
        ",\n".join(
            "  (%s::uuid, %s::text, %s::text, %s::text)"
            % (q(str(tid)), q(tt) if tt else "null", q(pos) if pos else "null", q(note))
            for tid, tt, pos, note in classified
        )
    )
    fx.append(") as v(id, technique_type, technique_position, note)")
    fx.append("where t.id = v.id and t.classification_status is null;\n")
    FIXES.write_text("\n".join(fx), encoding="utf-8", newline="\n")

    # ---- review report -------------------------------------------------------------------
    merged = [t for t in techniques.values() if len(t["sources"]) > 1]
    by_name = {}
    for (cat, name), t in techniques.items():
        by_name.setdefault(name, []).append(t)
    same_name_other_category = {n: ts for n, ts in by_name.items() if len(ts) > 1}

    final_names = [(corrected_name.get(t["id"], (None, t["name"]))[1], t["category"]) for t in techniques.values()]
    near = []
    for i in range(len(final_names)):
        for j in range(i + 1, len(final_names)):
            a, b = final_names[i], final_names[j]
            if norm(a[0]) == norm(b[0]):
                continue
            ratio = difflib.SequenceMatcher(None, norm(a[0]), norm(b[0])).ratio()
            if ratio >= 0.88:
                near.append((ratio, a, b))
    near.sort(reverse=True)

    typed = sum(1 for _, tt, _, _ in classified if tt)
    positioned = sum(1 for _, _, pos, _ in classified if pos)
    by_conf = {}
    for c in classification:
        if c["technique_type"] or c["position"]:
            by_conf[c["confidence"]] = by_conf.get(c["confidence"], 0) + 1

    out = [
        "# Relatório da importação do catálogo (US-005)",
        "",
        "Gerado por `scripts/catalog/generate_seed.py`. Origem: `%s` (abas Básico, Intermediário, Avançado)." % SOURCE,
        "Revisão declarada pelo dono do produto em 2026-10-20. Abas ocultas e `Material de Estudo` **não** foram importadas.",
        "",
        "## Totais",
        "- Linhas extraídas: **%d**" % len(rows),
        "- Técnicas únicas no catálogo global: **%d**" % len(techniques),
        "- Técnicas que aparecem em mais de um nível (nome e categoria idênticos): **%d**" % len(merged),
        "- Correções de digitação aplicadas: **%d** (`name_corrections.csv`)" % len(corrected_name),
        "- Classificadas com tipo: **%d**; com posição: **%d** (de %d). Confiança: %s"
        % (typed, positioned, len(techniques), ", ".join("%s %d" % (CONFIDENCE_PT[k], v) for k, v in sorted(by_conf.items()))),
        "",
        "## Correções de digitação aplicadas",
        "O nome original continua em `technique_sources.raw_name`. As técnicas mantêm a revisão.",
        "",
        "| Antes | Depois | Motivo |",
        "|---|---|---|",
    ]
    for old, new, reason in corrected_name.values():
        out.append("| %s | %s | %s |" % (old, new, reason))
    out += ["", "## Classificação (tipo e posição) — PROPOSTA, não validada", ""]
    out += [
        "Preenchida a partir de fontes públicas, **sem validação do mestre** (`classification_status = 'proposed'`).",
        "A categoria da planilha foi mantida. Regras e justificativa de cada linha em `classification.csv`.",
        "",
        "Fontes consultadas:",
        "- https://en.wikipedia.org/wiki/List_of_Brazilian_jiu-jitsu_techniques (classificação de quedas, finalizações, raspagens, posições)",
        "- https://www.kingz.com/pages/jiu-jitsu-dictionary (Katagatame = arm triangle, Relógio = clock choke, Toreando, upa, shrimp, posições)",
        "- https://bjjmore.com/brazilian-jiu-jitsu-submissions/ (estrangulamentos, chaves de braço/ombro e de perna; Baratoplata)",
        "",
        "Limites: nenhuma fonte consultada traz os nomes em português do Brasil de todas as técnicas; os termos locais",
        "(por exemplo `Barrigada`, `Mão de Vaca`, `Estrela`) ficam sem classificação ou só com a posição inferida da categoria.",
        "",
        "## Para você confirmar (NÃO alterados)",
        "",
        "| Categoria | Nome | Dúvida |",
        "|---|---|---|",
    ]
    for f in read_csv(FLAGGED):
        out.append("| %s | %s | %s |" % (f["category"], f["name"], f["question"]))
    out += ["", "## Nomes iguais em categorias diferentes (mantidos como técnicas distintas)"]
    if same_name_other_category:
        for n, ts in sorted(same_name_other_category.items()):
            out.append("- %s: %s" % (ts[0]["name"], "; ".join(sorted(t["category"] for t in ts))))
    else:
        out.append("- Nenhum.")
    out += ["", "## Grafias parecidas, NÃO fundidas (revisar com o mestre)", ""]
    if near:
        out += ["| Semelhança | Nome A | Categoria A | Nome B | Categoria B |", "|---|---|---|---|---|"]
        for ratio, a, b in near:
            out.append("| %.2f | %s | %s | %s | %s |" % (ratio, a[0], a[1], b[0], b[1]))
    else:
        out.append("Nenhuma.")
    out += [
        "",
        "## Observações sobre a origem",
        "- O número 45 aparece duas vezes em `Quedas` nas abas Básico e Intermediário; o número original é mantido em `technique_sources.source_number`.",
        "- Na aba Avançado o bloco `Chaves Membros Inferiores` é numerado de 90 a 94 (a numeração salta de 54 para 90).",
        "- Os nomes foram importados como escritos (apenas espaços normalizados) e só depois corrigidos pela migration `202610200009`.",
        "- A marca `x` e a contagem `Acertos` da planilha são controles de avaliação e não foram importadas.",
        "- A faixa citada em cada aba (BRANCA, AZUL, ROXA) fica na proveniência (`belt`); não foi interpretada como regra de graduação.",
        "",
    ]
    REPORT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(
        f"{len(techniques)} técnicas, {len(rows)} origens; {len(merged)} em mais de um nível; "
        f"{len(corrected_name)} correções; {typed} com tipo, {positioned} com posição; {len(near)} pares parecidos"
    )


if __name__ == "__main__":
    main()
